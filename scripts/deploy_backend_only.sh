#!/bin/bash
# ============================================================
# Roamio 后端部署脚本（服务器端执行）
# ============================================================
# 
# 用途：只部署后端代码（不包含前端）
# 前端通过 deploy_from_local.sh 从本地上传
#
# 使用方法：
# ssh acs@your-server
# cd /home/acs/roamio
# ./scripts/deploy_backend_only.sh
#
# ============================================================

set -e  # 遇到错误立即退出

echo "🚀 开始部署 Roamio 后端..."

# ============================================================
# 1. 拉取最新代码
# ============================================================
echo ""
echo "📥 [1/4] 拉取最新代码..."
git pull origin master

# ============================================================
# 2. 安装后端依赖
# ============================================================
echo ""
echo "📦 [2/4] 安装后端依赖..."
pip3 install -r requirements.txt

# ============================================================
# 3. 数据库迁移
# ============================================================
echo ""
echo "🗄️ [3/4] 数据库迁移..."
python3 manage.py migrate

# ============================================================
# 4. 收集 Django Admin 静态文件
# ============================================================
echo ""
echo "📋 [4/4] 收集 Django Admin 静态文件..."
python3 manage.py collectstatic --noinput

# ============================================================
# 5. 重启 uWSGI
# ============================================================
echo ""
echo "🔄 [5/5] 重启 uWSGI..."

# 方法 1：平滑重启（推荐）
if [ -f "uwsgi.pid" ]; then
    kill -HUP $(cat uwsgi.pid)
    echo "✅ uWSGI 平滑重启完成"
else
    # 方法 2：强制重启
    pkill -9 uwsgi || true
    uwsgi --ini scripts/uwsgi.ini --daemonize uwsgi.log
    echo "✅ uWSGI 重新启动完成"
fi

# ============================================================
# 完成
# ============================================================
echo ""
echo "🎉 后端部署完成！"
echo ""
echo "📊 部署信息："
echo "  - 后端 API: 已重启"
echo "  - Django Admin: 静态文件已更新"
echo ""
echo "⚠️  注意："
echo "  - 前端文件需要通过 deploy_from_local.sh 从本地上传"
echo "  - 前端位置: /home/acs/roamio/web/dist/"
echo ""

