#!/bin/bash
# ============================================================
# Roamio 部署脚本
# ============================================================

set -e  # 遇到错误立即退出

echo "🚀 开始部署 Roamio..."

# ============================================================
# 1. 拉取最新代码
# ============================================================
echo ""
echo "📥 [1/6] 拉取最新代码..."
git pull origin master

# ============================================================
# 2. 安装后端依赖
# ============================================================
echo ""
echo "📦 [2/6] 安装后端依赖..."
pip3 install -r requirements.txt

# ============================================================
# 3. 数据库迁移
# ============================================================
echo ""
echo "🗄️ [3/6] 数据库迁移..."
python3 manage.py migrate

# ============================================================
# 4. 构建前端
# ============================================================
echo ""
echo "🔨 [4/6] 构建前端..."
cd web
npm install
npm run build
cd ..

# ============================================================
# 5. 部署前端静态文件
# ============================================================
echo ""
echo "📋 [5/6] 部署前端静态文件..."

# 方案 A：复制到 Django static 目录（当前方案）
if [ -d "static/vue" ]; then
    rm -rf static/vue
fi
mkdir -p static/vue
cp -r web/dist/* static/vue/

# 收集 Django 静态文件（Admin 等）
python3 manage.py collectstatic --noinput

echo "✅ 前端文件已部署到: static/vue/"

# 方案 B：使用 Nginx 直接访问 dist 目录（未来可选）
# 如果使用 Nginx 直接访问 web/dist/，则不需要复制
# 只需要在 Nginx 配置中指向 web/dist/ 即可

# ============================================================
# 6. 重启 uWSGI
# ============================================================
echo ""
echo "🔄 [6/6] 重启 uWSGI..."

# 方法 1：平滑重启（推荐）
if [ -f "uwsgi.pid" ]; then
    kill -HUP $(cat uwsgi.pid)
    echo "✅ uWSGI 平滑重启完成"
else
    # 方法 2：强制重启
    pkill -9 uwsgi || true
    uwsgi --ini scripts/uwsgi.ini --daemonize uwsgi.log
    echo "✅ uWSGI 重新启动完成"
fi

# ============================================================
# 完成
# ============================================================
echo ""
echo "🎉 部署完成！"
echo ""
echo "📊 部署信息："
echo "  - 前端文件: static/vue/"
echo "  - 后端 API: 已重启"
echo "  - 访问地址: https://app7508.acapp.acwing.com.cn"
echo ""
echo "🧪 请测试以下功能："
echo "  1. 旅行列表加载"
echo "  2. 旅行详情查看"
echo "  3. 用户登录/注册"
echo "  4. 评论发布"
echo "  5. 图片上传"
echo ""

